class CatalogError(ValueError):
    """Fixed diagnostics only; never echo caller key strings."""


def validate_subscription(tr_id: str, tr_key: str, *, paper: bool = False) -> Channel:
    """Validate only a fixed public channel and a conservative symbol syntax.

    Does not prove symbol existence, account eligibility, entitlement, source
    freshness or permission to connect. No normalization or free-form TR IDs.
    """
    if type(tr_id) is not str or tr_id not in CHANNELS:
        raise CatalogError("KIS_LIVE_CHANNEL_NOT_ALLOWED")
    if type(paper) is not bool:
        raise CatalogError("KIS_LIVE_ENVIRONMENT_INVALID")
    channel = CHANNELS[tr_id]
    if paper and not channel.paper:
        raise CatalogError("KIS_LIVE_PAPER_UNSUPPORTED")
    if (type(tr_key) is not str or not tr_key.isascii() or len(tr_key) > 32
            or re.fullmatch(channel.key_pattern, tr_key) is None):
        raise CatalogError("KIS_LIVE_SUBSCRIPTION_KEY_INVALID")
    return channel


def subscription_delay_seconds(tr_id: str, tr_key: str) -> int:
    """Documented minimum feed delay; never a freshness/entitlement guarantee."""
    channel = validate_subscription(tr_id, tr_key)
    if tr_id == "HDFSCNT0" and tr_key[:4] in ("DTSE", "DHKS", "DSHS", "DSZS", "DHSX", "DHNX"):
        return 900
    return channel.delay_seconds


def companion_channel(tr_id: str, tr_key: str, *, paper: bool = False) -> Channel | None:
    """Return a pinned trade/book peer only if both accept this exact key/mode.

    No key rewriting, feed mixing, entitlement claim or atomic-snapshot claim.
    A legitimate single-channel subscription with no compatible peer stays single.
    """
    validate_subscription(tr_id, tr_key, paper=paper)
    peer = COMPANION_CHANNELS.get(tr_id)
    if peer is None:
        return None
    try:
        return validate_subscription(peer, tr_key, paper=paper)
    except CatalogError:
        return None
